"""PostgreSQL/PostGIS, Valkey, S3, and canonical P-code helpers for Food workers."""

from __future__ import annotations

import hashlib
import json
import os
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

BST = timezone(timedelta(hours=6))

FOOD_ROOT = Path(__file__).resolve().parents[2]
REPO_ROOT = Path(__file__).resolve().parents[5]
DATA_DIR = FOOD_ROOT / "data"
MIGRATION_SQL = FOOD_ROOT / "db" / "migrations" / "001_food_schema.sql"
DEFAULT_GEO_CODES_PATH = (
    REPO_ROOT.parent / "Aparajeyo_Doc" / "Documentaion" / "contracts" / "news_map" / "geo_codes.json"
)

DEFAULT_DATABASE_URL = "postgresql://food:food@127.0.0.1:5433/aparajeyo_food"
DEFAULT_VALKEY_URL = "valkey://127.0.0.1:6382/0"


def _load_food_env() -> None:
    # First value wins, so .env.local (generated by scripts/dev-up.sh) overrides .env.
    for env_path in (FOOD_ROOT / ".env.local", FOOD_ROOT / ".env"):
        if not env_path.exists():
            continue
        for line in env_path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())


_load_food_env()


def get_database_url() -> str:
    return os.environ.get("DATABASE_URL", DEFAULT_DATABASE_URL)


def get_valkey_url() -> str:
    return os.environ.get("VALKEY_URL", DEFAULT_VALKEY_URL)


def now_bst_iso() -> str:
    return datetime.now(BST).isoformat(timespec="seconds")


def today_bst_date() -> str:
    return datetime.now(BST).strftime("%Y-%m-%d")


def stable_uuid_v4(source: str, source_id: str) -> str:
    """Deterministic RFC 4122 UUID v4 derived from (source, source_id) (Rule R8)."""
    digest = bytearray(hashlib.sha256(f"{source}:{source_id}".encode("utf-8")).digest()[:16])
    digest[6] = (digest[6] & 0x0F) | 0x40
    digest[8] = (digest[8] & 0x3F) | 0x80
    return str(uuid.UUID(bytes=bytes(digest)))


def get_pg_connection() -> psycopg.Connection:
    conn = psycopg.connect(get_database_url(), row_factory=dict_row, autocommit=False)
    return conn


def ensure_schema(conn: psycopg.Connection) -> None:
    sql = MIGRATION_SQL.read_text(encoding="utf-8")
    with conn.cursor() as cur:
        cur.execute(sql)
    conn.commit()


def load_geo_codes(geo_path: Path = DEFAULT_GEO_CODES_PATH) -> dict:
    path = Path(os.environ.get("GEO_CODES_PATH", str(geo_path)))
    return json.loads(path.read_text(encoding="utf-8"))
