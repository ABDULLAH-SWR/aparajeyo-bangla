#!/usr/bin/env bash
# Starts the local Food stack. Generates .env.local with random secrets when it is absent.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

if [[ ! -f .env.local ]]; then
  command -v openssl >/dev/null || { echo "dev-up: openssl is required" >&2; exit 1; }
  secret() { openssl rand -hex 32; }
  postgres_password=$(secret)
  s3_key_suffix=$(openssl rand -hex 12)
  api_db_password=$(secret)
  worker_db_password=$(secret)
  umask 077
  {
    echo "# Generated by scripts/dev-up.sh. Never commit this file."
    echo "POSTGRES_PASSWORD=$postgres_password"
    echo "DATABASE_URL_OWNER=postgresql://food:$postgres_password@127.0.0.1:5433/aparajeyo_food?sslmode=disable"
    echo "FOOD_API_DB_PASSWORD=$api_db_password"
    echo "FOOD_WORKER_DB_PASSWORD=$worker_db_password"
    echo "DATABASE_URL=postgresql://food_api:$api_db_password@127.0.0.1:5433/aparajeyo_food"
    echo "IMGPROXY_KEY=$(secret)"
    echo "IMGPROXY_SALT=$(secret)"
    echo "S3_ACCESS_KEY=GK$s3_key_suffix"
    echo "S3_SECRET_KEY=$(secret)"
    echo "GARAGE_RPC_SECRET=$(secret)"
    echo "GARAGE_ADMIN_TOKEN=$(secret)"
    echo "DIRECTUS_SECRET=$(secret)"
    echo "DIRECTUS_ADMIN_EMAIL=admin@aparajeyo.local"
    echo "DIRECTUS_ADMIN_PASSWORD=$(secret)"
    echo "FOOD_INVALIDATE_TOKEN=$(secret)"
  } > .env.local.tmp
  mv .env.local.tmp .env.local
  {
    echo "# Generated by scripts/dev-up.sh. Never commit this file."
    echo "DATABASE_URL=postgresql://food_worker:$worker_db_password@127.0.0.1:5433/aparajeyo_food"
  } > workers/.env.local
  echo "dev-up: generated .env.local"
  echo "dev-up: an existing Postgres volume keeps its old password until you run ALTER USER." >&2
fi

# .env holds optional non-secret settings; .env.local is read last, so it wins.
env_files=()
[[ -f .env ]] && env_files+=(--env-file .env)
env_files+=(--env-file .env.local)

# A new volume starts empty. Migrations and role logins are explicit steps.
echo "dev-up: then run dbmate up (as DATABASE_URL_OWNER) and scripts/db-bootstrap-roles.sh" >&2

exec docker compose "${env_files[@]}" up -d "$@"
