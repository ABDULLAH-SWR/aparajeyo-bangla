#!/usr/bin/env bash
# Starts the local Food stack: `bun run dev:up`. Generates .env.local with random secrets when it is
# absent, and adds any non-secret dev setting that neither .env file defines.
# On Windows the stack runs in WSL, and this script then stays in the foreground to keep the WSL VM
# awake. Ctrl+C releases it; the containers are not stopped.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
source scripts/lib/stack.sh

wsl_distro=${FOOD_WSL_DISTRO:-Ubuntu}

# Git Bash with Docker only inside WSL: run this script there, then hold the VM open from here.
if docker_only_in_wsl; then
  wsl_dir=$(wsl_working_dir)
  MSYS_NO_PATHCONV=1 wsl.exe -d "$wsl_distro" -- env FOOD_DEV_KEEPALIVE=0 \
    bash -c 'cd "$1" && shift && exec bash scripts/dev-up.sh "$@"' dev-up "$wsl_dir" "$@"
  echo "dev-up: keeping WSL awake; press Ctrl+C to release" >&2
  MSYS_NO_PATHCONV=1 exec wsl.exe -d "$wsl_distro" -- sleep infinity
fi

if [[ ! -f .env.local ]]; then
  command -v openssl >/dev/null || { echo "dev-up: openssl is required" >&2; exit 1; }
  secret() { openssl rand -hex 32; }
  postgres_password=$(secret)
  api_db_password=$(secret)
  worker_db_password=$(secret)
  umask 077
  {
    echo "# Generated by scripts/dev-up.sh. Never commit this file."
    echo "POSTGRES_PASSWORD=$postgres_password"
    echo "DATABASE_URL_OWNER=postgresql://food:$postgres_password@127.0.0.1:5433/aparajeyo_food?sslmode=disable"
    echo "FOOD_API_DB_PASSWORD=$api_db_password"
    echo "FOOD_WORKER_DB_PASSWORD=$worker_db_password"
    echo "DATABASE_URL=postgresql://food_api:$api_db_password@127.0.0.1:5433/aparajeyo_food"
    echo "IMGPROXY_KEY=$(secret)"
    echo "IMGPROXY_SALT=$(secret)"
    echo "GARAGE_RPC_SECRET=$(secret)"
    echo "GARAGE_ADMIN_TOKEN=$(secret)"
    echo "DIRECTUS_SECRET=$(secret)"
    echo "DIRECTUS_ADMIN_EMAIL=admin@aparajeyo.local"
    echo "DIRECTUS_ADMIN_PASSWORD=$(secret)"
    echo "FOOD_INVALIDATE_TOKEN=$(secret)"
  } > .env.local.tmp
  mv .env.local.tmp .env.local
  {
    echo "# Generated by scripts/dev-up.sh. Never commit this file."
    echo "DATABASE_URL=postgresql://food_worker:$worker_db_password@127.0.0.1:5433/aparajeyo_food"
  } > workers/.env.local
  echo "dev-up: generated .env.local"
  echo "dev-up: an existing Postgres volume keeps its old password until you run ALTER USER." >&2
fi

# Non-secret settings the API requires (Guide Appendix E). An existing value is never changed.
ensure_setting() {
  grep -qs "^$1=" .env .env.local && return 0
  [[ -z "$(tail -c1 .env.local)" ]] || echo >> .env.local
  echo "$1=$2" >> .env.local
  echo "dev-up: added $1 to .env.local" >&2
}
ensure_setting NODE_ENV development
ensure_setting VALKEY_URL redis://127.0.0.1:6382/0
ensure_setting IMGPROXY_BASE_URL http://127.0.0.1:8081
ensure_setting CORS_ALLOWED_ORIGINS http://localhost:3000
ensure_setting FOOD_INTERNAL_BIND_ADDR 127.0.0.1
ensure_setting GEO_CODES_PATH data/geo_codes.v03.json
ensure_setting FOOD_API_BASE_URL http://127.0.0.1:8002
ensure_setting S3_ENDPOINT http://127.0.0.1:3900
ensure_setting S3_REGION ap-south-1
ensure_setting S3_BUCKET food-media
ensure_setting WIKIMEDIA_USER_AGENT "AparajeyoFoodSync/0.1 (https://aparajeyo.com)"
# Used by db-bootstrap-roles.sh and by the directus service.
ensure_setting DIRECTUS_DB_PASSWORD "$(openssl rand -hex 32)"
ensure_setting DIRECTUS_URL http://127.0.0.1:8055
# Garage creates its own keys. Compose needs the names to exist before garage-bootstrap.sh can run.
for name in S3_ACCESS_KEY S3_SECRET_KEY S3_IMGPROXY_ACCESS_KEY S3_IMGPROXY_SECRET_KEY; do
  ensure_setting "$name" not-yet-created
done

# .env holds optional non-secret settings; .env.local is read last, so it wins.
env_files=()
[[ -f .env ]] && env_files+=(--env-file .env)
env_files+=(--env-file .env.local)

# A new volume starts empty. Migrations and role logins are explicit steps.
echo "dev-up: then run dbmate up (as DATABASE_URL_OWNER) and scripts/db-bootstrap-roles.sh" >&2
echo "dev-up: for photos, run scripts/garage-bootstrap.sh once, put its keys in .env.local," >&2
echo "dev-up:   then run dev-up again" >&2
echo "dev-up: for Directus, after dbmate and the roles (the compose files need the same" >&2
echo "dev-up:   --env-file options):" >&2
echo "dev-up:   1. bun scripts/directus-bootstrap.ts register" >&2
echo "dev-up:   2. docker compose exec directus node cli.js schema apply --yes" \
  "/directus/food/snapshot.yaml" >&2
echo "dev-up:   3. bun scripts/directus-bootstrap.ts" >&2
echo "dev-up: the food-api service holds port 8002; stop it before 'bun run dev'" >&2

docker compose "${env_files[@]}" up -d "$@"

# Started from Windows through the WSL `bash` launcher: the VM stops when its last process exits.
if [[ -n "${WSL_DISTRO_NAME:-}" && "${FOOD_DEV_KEEPALIVE:-1}" == 1 ]]; then
  echo "dev-up: keeping WSL awake; press Ctrl+C to release" >&2
  exec sleep infinity
fi
